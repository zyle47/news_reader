_PASSAGE_ID = re.compile(r"^[a-z0-9](?:[a-z0-9_-]{0,62}[a-z0-9])?$")
_FAKE_NOTICE = (
    "Generated by a deterministic fake speech engine. This report verifies plumbing only; "
    "it is not evidence of naturalness, pronunciation quality, or language acceptance."
)
_TECHNICAL_NOTICE = (
    "This is a technical benchmark report. Voice quality still requires the documented "
    "long-form evaluation and acceptance by a fluent listener."
)


class EvaluationError(RuntimeError):
    """Raised when an evaluation cannot produce trustworthy artifacts."""


class EvidenceKind(StrEnum):
    """The limited conclusion an automated evaluation report can support."""

    FAKE_FUNCTIONAL_ONLY = "fake_functional_only"
    TECHNICAL_BENCHMARK_ONLY = "technical_benchmark_only"


@dataclass(frozen=True, slots=True)
class LoadMetrics:
    cold_wall_seconds: float
    cold_cpu_seconds: float
    warm_wall_seconds: float
    warm_cpu_seconds: float
    rss_before_bytes: int | None
    rss_after_cold_bytes: int | None
    rss_after_warm_bytes: int | None

    def __post_init__(self) -> None:
        for field_name in (
            "cold_wall_seconds",
            "cold_cpu_seconds",
            "warm_wall_seconds",
            "warm_cpu_seconds",
        ):
            value = getattr(self, field_name)
            if not isinstance(value, float) or not math.isfinite(value) or value < 0:
                raise ValueError(f"{field_name} must be a finite non-negative float")
        for field_name in (
            "rss_before_bytes",
            "rss_after_cold_bytes",
            "rss_after_warm_bytes",
        ):
            value = getattr(self, field_name)
            if value is not None and (
                isinstance(value, bool) or not isinstance(value, int) or value < 0
            ):
                raise ValueError(f"{field_name} must be a non-negative integer or null")

    def to_dict(self) -> dict[str, float | int | None]:
        return {
            "cold_wall_seconds": self.cold_wall_seconds,
            "cold_cpu_seconds": self.cold_cpu_seconds,
            "warm_wall_seconds": self.warm_wall_seconds,
            "warm_cpu_seconds": self.warm_cpu_seconds,
            "rss_before_bytes": self.rss_before_bytes,
            "rss_after_cold_bytes": self.rss_after_cold_bytes,
            "rss_after_warm_bytes": self.rss_after_warm_bytes,
        }


@dataclass(frozen=True, slots=True)
class EvaluationSample:
    passage_id: str
    language: str
    script: str
    wav_filename: str
    text_characters: int
    text_sha256: str
    wav_sha256: str
    audio_duration_seconds: float
    generation_wall_seconds: float
    generation_cpu_seconds: float
    generation_cpu_percent: float | None
    real_time_factor: float
    time_to_first_audio_seconds: float | None
    time_to_first_audio_note: str
    rss_before_bytes: int | None
    rss_after_bytes: int | None

    def __post_init__(self) -> None:
        if _PASSAGE_ID.fullmatch(self.passage_id) is None:
            raise ValueError("invalid passage ID in evaluation sample")
        try:
            Language(self.language)
        except ValueError as error:
            raise ValueError("language must be a supported Language value") from error
        try:
            Script(self.script)
        except ValueError as error:
            raise ValueError("script must be a supported Script value") from error
        if (
            not self.wav_filename.endswith(".wav")
            or Path(self.wav_filename).name != self.wav_filename
        ):
            raise ValueError("wav_filename must be a relative controlled filename")
        if (
            isinstance(self.text_characters, bool)
            or not isinstance(self.text_characters, int)
            or self.text_characters <= 0
        ):
            raise ValueError("text_characters must be positive")
        for field_name in ("text_sha256", "wav_sha256"):
            value = getattr(self, field_name)
            if (
                not isinstance(value, str)
                or len(value) != 64
                or any(character not in "0123456789abcdef" for character in value)
            ):
                raise ValueError(f"{field_name} must be a lowercase SHA-256 digest")
        for field_name in (
            "audio_duration_seconds",
            "generation_wall_seconds",
            "generation_cpu_seconds",
            "real_time_factor",
        ):
            value = getattr(self, field_name)
            if not isinstance(value, float) or not math.isfinite(value) or value < 0:
                raise ValueError(f"{field_name} must be a finite non-negative float")
        if self.audio_duration_seconds <= 0:
            raise ValueError("audio_duration_seconds must be positive")
        if self.generation_cpu_percent is not None and (
            not isinstance(self.generation_cpu_percent, float)
            or not math.isfinite(self.generation_cpu_percent)
            or self.generation_cpu_percent < 0
        ):
            raise ValueError("generation_cpu_percent must be finite, non-negative, or null")
        if self.time_to_first_audio_seconds is not None and (
            not isinstance(self.time_to_first_audio_seconds, float)
            or not math.isfinite(self.time_to_first_audio_seconds)
            or self.time_to_first_audio_seconds < 0
        ):
            raise ValueError("time_to_first_audio_seconds must be finite, non-negative, or null")
        if not self.time_to_first_audio_note:
            raise ValueError("time_to_first_audio_note must explain the measurement")
        for field_name in ("rss_before_bytes", "rss_after_bytes"):
            value = getattr(self, field_name)
            if value is not None and (
                isinstance(value, bool) or not isinstance(value, int) or value < 0
            ):
                raise ValueError(f"{field_name} must be a non-negative integer or null")

    def to_dict(self) -> dict[str, str | int | float | None]:
        return {
            "passage_id": self.passage_id,
            "language": self.language,
            "script": self.script,
            "wav_filename": self.wav_filename,
            "text_characters": self.text_characters,
            "text_sha256": self.text_sha256,
            "wav_sha256": self.wav_sha256,
            "audio_duration_seconds": self.audio_duration_seconds,
            "generation_wall_seconds": self.generation_wall_seconds,
            "generation_cpu_seconds": self.generation_cpu_seconds,
            "generation_cpu_percent": self.generation_cpu_percent,
            "real_time_factor": self.real_time_factor,
            "time_to_first_audio_seconds": self.time_to_first_audio_seconds,
            "time_to_first_audio_note": self.time_to_first_audio_note,
            "rss_before_bytes": self.rss_before_bytes,
            "rss_after_bytes": self.rss_after_bytes,
        }


