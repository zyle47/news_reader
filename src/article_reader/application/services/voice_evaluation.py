@dataclass(frozen=True, slots=True)
class VoiceEvaluationReport:
    schema_version: int
    created_at_utc: str
    run_id: str
    report_filename: str
    voice_contract: VoiceContractSnapshot
    runtime: RuntimeSnapshot
    evidence_kind: EvidenceKind
    quality_evidence: bool
    notice: str
    load_metrics: LoadMetrics
    samples: tuple[EvaluationSample, ...]

    def __post_init__(self) -> None:
        if self.schema_version != 3:
            raise ValueError("unsupported evaluation report schema")
        if _PASSAGE_ID.fullmatch(self.run_id) is None:
            raise ValueError("run_id must be a controlled lowercase identifier")
        if (
            not self.report_filename.endswith(".json")
            or Path(self.report_filename).name != self.report_filename
        ):
            raise ValueError("report_filename must be a relative controlled filename")
        if not isinstance(self.evidence_kind, EvidenceKind):
            raise ValueError("evidence_kind must be an EvidenceKind enum")
        if self.quality_evidence is not False:
            raise ValueError("automated benchmark reports cannot claim voice-quality evidence")
        if not self.notice:
            raise ValueError("evaluation report requires an evidence notice")
        if not self.samples:
            raise ValueError("evaluation report requires at least one sample")

    def to_dict(self) -> dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "created_at_utc": self.created_at_utc,
            "run_id": self.run_id,
            "report_filename": self.report_filename,
            "voice": self.voice_contract.to_dict(),
            "runtime": self.runtime.to_dict(),
            "evidence": {
                "kind": self.evidence_kind.value,
                "quality_evidence": self.quality_evidence,
                "notice": self.notice,
            },
            "load": self.load_metrics.to_dict(),
            "samples": [sample.to_dict() for sample in self.samples],
        }

    @property
    def run_directory_name(self) -> str:
        return self.run_id

    @property
    def voice_id(self) -> str:
        return self.voice_contract.voice_id

    @property
    def registry_evaluation_status(self) -> str:
        return self.voice_contract.registry_evaluation_status

    @property
    def engine_id(self) -> str:
        return self.voice_contract.engine_id

    @property
    def engine_version(self) -> str:
        return self.voice_contract.engine_version


MonotonicClock = Callable[[], float]
UtcClock = Callable[[], datetime]
RssReader = Callable[[], int | None]
RuntimeReader = Callable[[], RuntimeSnapshot]
RunIdFactory = Callable[[], str]


def _utc_now() -> datetime:
    return datetime.now(UTC)


def _format_utc(value: datetime) -> str:
    if value.tzinfo is None or value.utcoffset() is None:
        raise EvaluationError("UTC clock must return a timezone-aware datetime")
    return value.astimezone(UTC).isoformat(timespec="seconds").replace("+00:00", "Z")


def _runtime_snapshot() -> RuntimeSnapshot:
    probe = SystemDiagnosticProbe()
    return RuntimeSnapshot(
        operating_system=platform.platform(),
        architecture=platform.machine(),
        python_version=platform.python_version(),
        sqlite_version=sqlite3.sqlite_version,
        logical_cpus=os.cpu_count(),
        total_ram_bytes=probe.total_memory_bytes(),
        rss_measurement_kind=(
            "current_working_set_bytes" if os.name == "nt" else "current_or_max_rss_bytes"
        ),
    )


def _new_run_id() -> str:
    return f"run-{uuid.uuid4().hex}"


def _voice_contract(
    voice: VoiceSpec,
    settings: SpeechSettings,
    engine_id: str,
    engine_version: str,
) -> VoiceContractSnapshot:
    content: dict[str, Any] = {
        "voice_id": voice.voice_id,
        "display_name": voice.display_name,
        "language": voice.language.value,
        "scripts": [script.value for script in voice.scripts],
        "registry_evaluation_status": voice.evaluation_status.value,
        "engine": {"id": engine_id, "version": engine_version},
        "sample_rate_hz": voice.sample_rate_hz,
        "source": {"url": voice.source_url, "revision": voice.source_revision},
        "model": {"url": voice.model_url, "sha256": voice.model_sha256},
        "config": {"url": voice.config_url, "sha256": voice.config_sha256},
        "licenses": {
            "model": voice.model_license_url,
            "data": voice.data_license_url,
        },
        "settings": dict(settings.options),
    }
    canonical = json.dumps(
        content,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    ).encode("utf-8")
    return VoiceContractSnapshot(
        voice_id=voice.voice_id,
        display_name=voice.display_name,
        language=voice.language.value,
        scripts=tuple(script.value for script in voice.scripts),
        registry_evaluation_status=voice.evaluation_status.value,
        engine_id=engine_id,
        engine_version=engine_version,
        sample_rate_hz=voice.sample_rate_hz,
        source_url=voice.source_url,
        source_revision=voice.source_revision,
        model_url=voice.model_url,
        model_sha256=voice.model_sha256,
        config_url=voice.config_url,
        config_sha256=voice.config_sha256,
        model_license_url=voice.model_license_url,
        data_license_url=voice.data_license_url,
        settings=settings.options,
        contract_sha256=hashlib.sha256(canonical).hexdigest(),
    )


def _windows_rss_bytes() -> int | None:
    if os.name != "nt":
        return None

    class ProcessMemoryCounters(ctypes.Structure):
        _fields_ = [
            ("cb", ctypes.c_ulong),
            ("PageFaultCount", ctypes.c_ulong),
            ("PeakWorkingSetSize", ctypes.c_size_t),
            ("WorkingSetSize", ctypes.c_size_t),
            ("QuotaPeakPagedPoolUsage", ctypes.c_size_t),
            ("QuotaPagedPoolUsage", ctypes.c_size_t),
            ("QuotaPeakNonPagedPoolUsage", ctypes.c_size_t),
            ("QuotaNonPagedPoolUsage", ctypes.c_size_t),
            ("PagefileUsage", ctypes.c_size_t),
            ("PeakPagefileUsage", ctypes.c_size_t),
        ]

    try:
        counters = ProcessMemoryCounters()
        counters.cb = ctypes.sizeof(counters)
        kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
        psapi = ctypes.WinDLL("psapi", use_last_error=True)
        kernel32.GetCurrentProcess.restype = ctypes.c_void_p
        psapi.GetProcessMemoryInfo.argtypes = [
            ctypes.c_void_p,
            ctypes.POINTER(ProcessMemoryCounters),
            ctypes.c_ulong,
        ]
        psapi.GetProcessMemoryInfo.restype = ctypes.c_int
        process = kernel32.GetCurrentProcess()
        success = psapi.GetProcessMemoryInfo(
            process,
            ctypes.byref(counters),
            counters.cb,
        )
        if not success:
            return None
        return int(counters.WorkingSetSize)
    except (AttributeError, OSError, ValueError):
        return None


def _posix_rss_bytes() -> int | None:
    if os.name == "nt":
        return None
    if sys.platform.startswith("linux"):
        try:
            fields = Path("/proc/self/statm").read_text(encoding="ascii").split()
            resident_pages = int(fields[1])
            page_size = int(os.sysconf("SC_PAGE_SIZE"))
            return resident_pages * page_size
        except (IndexError, OSError, TypeError, ValueError):
            pass
    try:
        import resource

        maximum_rss = int(
            resource.getrusage(resource.RUSAGE_SELF).ru_maxrss  # type: ignore[attr-defined]
        )
        return maximum_rss if sys.platform == "darwin" else maximum_rss * 1024
    except (ImportError, OSError, ValueError):
        return None


def current_rss_bytes() -> int | None:
    """Return current/maximum resident bytes where the stdlib exposes them."""

    return _windows_rss_bytes() if os.name == "nt" else _posix_rss_bytes()


def _validate_wav(path: Path, expected: AudioResult) -> None:
    try:
        with wave.open(str(path), "rb") as wav_file:
            if wav_file.getcomptype() != "NONE":
                raise EvaluationError("evaluation WAV is not uncompressed PCM")
            if wav_file.getnchannels() != expected.channels:
                raise EvaluationError("evaluation WAV channel count changed during publication")
            if wav_file.getsampwidth() != expected.sample_width_bytes:
                raise EvaluationError("evaluation WAV sample width changed during publication")
            if wav_file.getframerate() != expected.sample_rate_hz:
                raise EvaluationError("evaluation WAV sample rate changed during publication")
            if wav_file.getnframes() != expected.frame_count:
                raise EvaluationError("evaluation WAV frame count changed during publication")
            if wav_file.readframes(expected.frame_count) != expected.pcm_bytes:
                raise EvaluationError("evaluation WAV PCM payload failed verification")
    except (OSError, EOFError, wave.Error) as error:
        raise EvaluationError("evaluation WAV failed validation") from error


def _write_wav_atomically(destination: Path, audio: AudioResult) -> str:
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{destination.stem}-",
        suffix=".tmp",
        dir=destination.parent,
    )
    temporary_path = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as raw_file:
            with wave.open(raw_file, "wb") as wav_file:
                wav_file.setnchannels(audio.channels)
                wav_file.setsampwidth(audio.sample_width_bytes)
                wav_file.setframerate(audio.sample_rate_hz)
                wav_file.writeframes(audio.pcm_bytes)
            raw_file.flush()
            os.fsync(raw_file.fileno())
        _validate_wav(temporary_path, audio)
        wav_sha256 = hashlib.sha256(temporary_path.read_bytes()).hexdigest()
        os.replace(temporary_path, destination)
        return wav_sha256
    finally:
        temporary_path.unlink(missing_ok=True)


def _write_json_atomically(destination: Path, document: dict[str, Any]) -> None:
    encoded = (json.dumps(document, ensure_ascii=False, indent=2, sort_keys=True) + "\n").encode(
        "utf-8"
    )
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{destination.stem}-",
        suffix=".tmp",
        dir=destination.parent,
    )
    temporary_path = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "wb") as raw_file:
            raw_file.write(encoded)
            raw_file.flush()
            os.fsync(raw_file.fileno())
        json.loads(temporary_path.read_text(encoding="utf-8"))
        os.replace(temporary_path, destination)
    finally:
        temporary_path.unlink(missing_ok=True)


class VoiceEvaluationService:
    """Evaluate one exact voice without changing its approval state."""

    def __init__(
        self,
        engine: SpeechEngine,
        *,
        wall_clock: MonotonicClock = time.perf_counter,
        cpu_clock: MonotonicClock = time.process_time,
        utc_clock: UtcClock = _utc_now,
        rss_reader: RssReader = current_rss_bytes,
        runtime_reader: RuntimeReader = _runtime_snapshot,
        run_id_factory: RunIdFactory = _new_run_id,
    ) -> None:
        self._engine = engine
        self._wall_clock = wall_clock
        self._cpu_clock = cpu_clock
        self._utc_clock = utc_clock
        self._rss_reader = rss_reader
        self._runtime_reader = runtime_reader
        self._run_id_factory = run_id_factory

    def _read_rss(self) -> int | None:
        try:
            return self._rss_reader()
        except Exception:
            return None

    def evaluate(
        self,
        voice: VoiceSpec,
        passages: Sequence[EvaluationPassage],
        output_directory: Path,
        settings: SpeechSettings | None = None,
    ) -> VoiceEvaluationReport:
        if not isinstance(voice, VoiceSpec):
            raise EvaluationError("evaluation requires a validated VoiceSpec")
        supplied_passages = tuple(passages)
        if not supplied_passages:
            raise EvaluationError("evaluation requires at least one passage")
        if any(not isinstance(passage, EvaluationPassage) for passage in supplied_passages):
            raise EvaluationError("passages must contain only EvaluationPassage values")
        passage_ids = [passage.passage_id for passage in supplied_passages]
        if len(set(passage_ids)) != len(passage_ids):
            raise EvaluationError("evaluation passage IDs must be unique")
        for passage in supplied_passages:
            if not voice.supports(passage.language, passage.script):
                raise EvaluationError(
                    f"passage {passage.passage_id!r} is not supported by voice {voice.voice_id!r}"
                )

        synthesis_settings = settings if settings is not None else SpeechSettings()
        if not isinstance(synthesis_settings, SpeechSettings):
            raise EvaluationError("settings must be a validated SpeechSettings value")

        try:
            descriptor = self._engine.descriptor
        except Exception as error:
            raise EvaluationError("speech engine identity is unavailable") from error
        if not descriptor.is_test_double:
            if descriptor.engine_id != voice.engine:
                raise EvaluationError(
                    f"engine {descriptor.engine_id!r} cannot evaluate voice for {voice.engine!r}"
                )
            if descriptor.engine_version != voice.engine_version:
                raise EvaluationError(
                    "loaded engine version does not match the registry's pinned engine version"
                )

        destination_directory = Path(output_directory)
        try:
            destination_directory.mkdir(parents=True, exist_ok=True)
        except OSError as error:
            raise EvaluationError("cannot create the evaluation output directory") from error
        if not destination_directory.is_dir():
            raise EvaluationError("evaluation output path is not a directory")

        created_at = _format_utc(self._utc_clock())
        run_id = self._run_id_factory()
        if not isinstance(run_id, str) or _PASSAGE_ID.fullmatch(run_id) is None:
            raise EvaluationError("run ID factory returned an invalid identifier")
        try:
            runtime_snapshot = self._runtime_reader()
        except Exception as error:
            raise EvaluationError("could not record the evaluation runtime") from error
        if not isinstance(runtime_snapshot, RuntimeSnapshot):
            raise EvaluationError("runtime reader returned an invalid snapshot")
        evidence_kind = (
            EvidenceKind.FAKE_FUNCTIONAL_ONLY
            if descriptor.is_test_double
            else EvidenceKind.TECHNICAL_BENCHMARK_ONLY
        )
        notice = _FAKE_NOTICE if descriptor.is_test_double else _TECHNICAL_NOTICE
        voice_contract = _voice_contract(
            voice,
            synthesis_settings,
            descriptor.engine_id,
            descriptor.engine_version,
        )

        try:
            staging_directory = Path(
                tempfile.mkdtemp(prefix=f".{run_id}-", dir=destination_directory)
            )
        except OSError as error:
            raise EvaluationError("cannot create an evaluation staging directory") from error
        final_directory = destination_directory / run_id
        engine_closed = False

        try:
            self._engine.close()
            engine_closed = True
            rss_before = self._read_rss()

            cold_wall_start = self._wall_clock()
            cold_cpu_start = self._cpu_clock()
            engine_closed = False
            self._engine.load(voice)
            cold_cpu_seconds = self._cpu_clock() - cold_cpu_start
            cold_wall_seconds = self._wall_clock() - cold_wall_start
            rss_after_cold = self._read_rss()

            warm_wall_start = self._wall_clock()
            warm_cpu_start = self._cpu_clock()
            self._engine.load(voice)
            warm_cpu_seconds = self._cpu_clock() - warm_cpu_start
            warm_wall_seconds = self._wall_clock() - warm_wall_start
            rss_after_warm = self._read_rss()

            load_metrics = LoadMetrics(
                cold_wall_seconds=float(cold_wall_seconds),
                cold_cpu_seconds=float(cold_cpu_seconds),
                warm_wall_seconds=float(warm_wall_seconds),
                warm_cpu_seconds=float(warm_cpu_seconds),
                rss_before_bytes=rss_before,
                rss_after_cold_bytes=rss_after_cold,
                rss_after_warm_bytes=rss_after_warm,
            )

            samples: list[EvaluationSample] = []
            for passage in supplied_passages:
                sample_rss_before = self._read_rss()
                generation_wall_start = self._wall_clock()
                generation_cpu_start = self._cpu_clock()
                try:
                    audio = self._engine.synthesize(passage.text, synthesis_settings)
                except Exception as error:
                    raise EvaluationError(
                        f"speech engine failed for passage {passage.passage_id!r}"
                    ) from error
                generation_cpu_seconds = self._cpu_clock() - generation_cpu_start
                generation_wall_seconds = self._wall_clock() - generation_wall_start
                sample_rss_after = self._read_rss()

                if not isinstance(audio, AudioResult):
                    raise EvaluationError("speech engine returned an invalid audio result type")
                if audio.duration_seconds <= 0:
                    raise EvaluationError("speech engine returned zero-duration audio")
                if audio.sample_rate_hz != voice.sample_rate_hz:
                    raise EvaluationError(
                        "speech engine sample rate does not match the registered voice contract"
                    )

                wav_filename = f"{voice.voice_id}--{passage.passage_id}.wav"
                wav_sha256 = _write_wav_atomically(
                    staging_directory / wav_filename,
                    audio,
                )
                wall_seconds = float(generation_wall_seconds)
                cpu_seconds = float(generation_cpu_seconds)
                samples.append(
                    EvaluationSample(
                        passage_id=passage.passage_id,
                        language=passage.language.value,
                        script=passage.script.value,
                        wav_filename=wav_filename,
                        text_characters=len(passage.text),
                        text_sha256=hashlib.sha256(passage.text.encode("utf-8")).hexdigest(),
                        wav_sha256=wav_sha256,
                        audio_duration_seconds=float(audio.duration_seconds),
                        generation_wall_seconds=wall_seconds,
                        generation_cpu_seconds=cpu_seconds,
                        generation_cpu_percent=(
                            cpu_seconds / wall_seconds * 100 if wall_seconds > 0 else None
                        ),
                        real_time_factor=wall_seconds / audio.duration_seconds,
                        time_to_first_audio_seconds=None,
                        time_to_first_audio_note=(
                            "Unavailable: the current engine port returns complete PCM only."
                        ),
                        rss_before_bytes=sample_rss_before,
                        rss_after_bytes=sample_rss_after,
                    )
                )

            try:
                self._engine.close()
            except Exception as error:
                raise EvaluationError("speech engine failed to close after evaluation") from error
            engine_closed = True

            report_filename = f"{voice.voice_id}--evaluation.json"
            report = VoiceEvaluationReport(
                schema_version=3,
                created_at_utc=created_at,
                run_id=run_id,
                report_filename=report_filename,
                voice_contract=voice_contract,
                runtime=runtime_snapshot,
                evidence_kind=evidence_kind,
                quality_evidence=False,
                notice=notice,
                load_metrics=load_metrics,
                samples=tuple(samples),
            )
            _write_json_atomically(
                staging_directory / report_filename,
                report.to_dict(),
            )
            if final_directory.exists():
                raise EvaluationError("evaluation run ID already exists")
            os.replace(staging_directory, final_directory)
            return report
        except EvaluationError:
            raise
        except Exception as error:
            raise EvaluationError("voice evaluation failed") from error
        finally:
            active_failure = sys.exc_info()[0] is not None
            if not engine_closed:
                try:
                    self._engine.close()
                except Exception as close_error:
                    if not active_failure:
                        raise EvaluationError("speech engine failed to close") from close_error
            if staging_directory.exists():
                shutil.rmtree(staging_directory, ignore_errors=True)
